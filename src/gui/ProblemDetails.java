public ProblemDetails(int problemId) {
    initComponents();
    setExtendedState(javax.swing.JFrame.MAXIMIZED_BOTH);

    for (Data.ProblemData p : ProblemDAO.getAllProblems()) {
        if (p.id == problemId) {

            problemIdValueLabel.setText(String.valueOf(p.id));
            studentIdValueLabel.setText(p.studentId);
            firstNameValueLabel.setText(p.firstName);
            lastNameValueLabel.setText(p.lastName);
            phoneNumberValueLabel.setText(p.phoneNumber);

            String problemName = "OTHERS".equalsIgnoreCase(p.problem)
                    && p.otherProblem != null
                    && !p.otherProblem.trim().isEmpty()
                    ? p.otherProblem
                    : p.problem;

            problemValueLabel.setText(problemName);
            buildingValueLabel.setText(p.building);
            roomValueLabel.setText(p.room);
            locationDescriptionValueLabel.setText(p.locationDescription);
            statusValueLabel.setText(p.status);

            // Unfixed Reason
            unfixedReasonValueLabel.setText(
                    p.unfixedReason == null || p.unfixedReason.trim().isEmpty()
                    ? "Not applicable" : p.unfixedReason
            );

            // Date Reported
            dateReported.setText(
                    p.dateReported == null || p.dateReported.trim().isEmpty()
                    ? "No date recorded" : p.dateReported
            );

            // Date Accepted
            dateAcceptedValueLabel.setText(
                    p.dateAccepted == null || p.dateAccepted.trim().isEmpty()
                    ? "Not yet accepted" : p.dateAccepted
            );

            // Date Fixed
            dateFixedValueLabel.setText(
                    p.fixedDate == null || p.fixedDate.trim().isEmpty()
                    ? "Not yet completed" : p.fixedDate
            );

            // Date Unfixed
            dateUnfixedValueLabel.setText(
                    p.dateUnfixed == null || p.dateUnfixed.trim().isEmpty()
                    ? "Not marked as unfixed" : p.dateUnfixed
            );

            break;
        }
    }
}
