    private void problemTableMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_problemTableMouseClicked

        int selectedRow = problemTable.getSelectedRow();

        if (selectedRow == -1) {
            return;
        }

        // Column 1 = ID
        int problemId = Integer.parseInt(
            problemTable.getValueAt(selectedRow, 1).toString()
        );

        // Column 6 = Status
        String status = problemTable.getValueAt(selectedRow, 6).toString();

        if (status.equals("Pending")) {

            Pending pending = new Pending(problemId);
            pending.setVisible(true);
            this.dispose();

        } else if (status.equals("In Progress")) {

            InProgress inProgress = new InProgress(problemId);
            inProgress.setVisible(true);
            this.dispose();
        }
    }//GEN-LAST:event_problemTableMouseClicked

    private void storebuttonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_storebuttonActionPerformed
    int selectedRow = problemTable.getSelectedRow();

if (selectedRow == -1) {
    javax.swing.JOptionPane.showMessageDialog(
            this,
            "Please select a problem first."
    );
    return;
}

// Column 1 = actual database Problem ID
int problemId = Integer.parseInt(
        problemTable.getValueAt(selectedRow, 1).toString()
);

// Confirm
int choice = javax.swing.JOptionPane.showConfirmDialog(
        this,
        "Are you sure you want to unarchive this problem?",
        "Confirm Unarchive",
        javax.swing.JOptionPane.YES_NO_OPTION
);

if (choice != javax.swing.JOptionPane.YES_OPTION) {
    return;
}

// Unarchive
boolean unarchived =
        ProblemDAO.unarchiveProblem(problemId);

if (unarchived) {

    javax.swing.JOptionPane.showMessageDialog(
            this,
            "Problem unarchived successfully."
    );

    loadArchivedProblems();

} else {

    javax.swing.JOptionPane.showMessageDialog(
            this,
            "Unable to unarchive the problem."
    );
}
    }//GEN-LAST:event_storebuttonActionPerformed

