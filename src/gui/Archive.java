   private void loadArchivedProblems() {

    javax.swing.table.DefaultTableModel model =
            (javax.swing.table.DefaultTableModel) problemTable.getModel();

    model.setRowCount(0);

    int no = 1;

    for (Data.ProblemData p : ProblemDAO.getArchivedProblems()) {

        model.addRow(new Object[]{
            no,
            p.id,
            p.studentId,
            p.problem,
            p.building,
            p.room,
            p.status
        });

        no++;
    }
}
