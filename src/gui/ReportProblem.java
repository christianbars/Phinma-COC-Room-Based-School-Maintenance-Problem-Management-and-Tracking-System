    private void submitButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_submitButtonActionPerformed

      String firstName = firstNameField.getText().trim();
    String lastName = lastNameField.getText().trim();
    String phoneNumber = phoneNumberField.getText().trim();

    String building = (String) buildingComboBox.getSelectedItem();
    String roomType = (String) problemTypeComboBox.getSelectedItem();
    String room = roomField.getText().trim();

    String problem = (String) problemComboBox.getSelectedItem();
    String locationDescription =
            locationDescriptionField.getText().trim();

    String otherProblem = otherProblemField.getText().trim();

    // Validate student ID
    if (studentId == null || studentId.trim().isEmpty()) {
        JOptionPane.showMessageDialog(
                this,
                "Student ID is missing.",
                "Invalid Student ID",
                JOptionPane.WARNING_MESSAGE
        );
        return;
    }

    // Validate required fields
   
if (firstName.isEmpty()
        || firstName.equalsIgnoreCase("Enter first name")
        || lastName.isEmpty()
        || lastName.equalsIgnoreCase("Enter last name")
        || phoneNumber.isEmpty()
        || phoneNumber.equals("09)()()()()()()()()()")
        || building == null
        || roomType == null
        || room.isEmpty()
        || room.equalsIgnoreCase("e.g Room 403 / Fourth Floor")
        || problem == null
        || locationDescription.isEmpty()
        || locationDescription.equalsIgnoreCase(
                "Describe the exact location and what is wrong.")) {

    JOptionPane.showMessageDialog(
            this,
            "Please fill in all required fields.",
            "Missing Information",
            JOptionPane.WARNING_MESSAGE
    );
    return;
}

    // Validate phone number
    if (!phoneNumber.matches("09\\d{9}")) {
        JOptionPane.showMessageDialog(
                this,
                "Phone number must be 11 digits and start with 09.",
                "Invalid Phone Number",
                JOptionPane.WARNING_MESSAGE
        );
        return;
    }

    // Validate Others
    if ("OTHERS".equalsIgnoreCase(problem)
            && otherProblem.isEmpty()) {

        JOptionPane.showMessageDialog(
                this,
                "Please specify the problem.",
                "Missing Problem Details",
                JOptionPane.WARNING_MESSAGE
        );
        return;
    }

    // Get database IDs from dropdown maps
    Integer buildingId = buildingIds.get(building);
    Integer roomTypeId = roomTypeIds.get(roomType);
    Integer problemTypeId =
            problemTypeIds.get(problem.trim().toUpperCase());

    if (buildingId == null || roomTypeId == null
            || problemTypeId == null) {

        JOptionPane.showMessageDialog(
                this,
                "Unable to identify the selected options. "
                + "Please check the dropdowns.",
                "Invalid Selection",
                JOptionPane.WARNING_MESSAGE
        );
        return;
    }

    // Create the problem object
    Data.ProblemData p = new Data.ProblemData(
            0,
            studentId.trim(),
            firstName,
            lastName,
            phoneNumber,
            problem,
            building,
            room,
            locationDescription
    );

    // Set database IDs
    p.buildingId = buildingId;
    p.roomTypeId = roomTypeId;
    p.problemTypeId = problemTypeId;

    // Save custom problem details only when OTHERS is selected
    p.otherProblem = "OTHERS".equalsIgnoreCase(problem)
            ? otherProblem
            : "";

    // Save to MySQL and check the result
    if (ProblemDAO.addProblem(p)) {

        JOptionPane.showMessageDialog(
                this,
                "Problem reported successfully!",
                "Success",
                JOptionPane.INFORMATION_MESSAGE
        );

        StudentDashboard dashboard =
                new StudentDashboard(studentId, firstName);

        dashboard.setVisible(true);
        this.dispose();

    } else {

        JOptionPane.showMessageDialog(
                this,
                "This report could not be saved. "
                + "The problem may already have been reported "
                + "or a database error may have occurred.",
                "Report Not Saved",
                JOptionPane.WARNING_MESSAGE
        );
    }
    }//GEN-LAST:event_submitButtonActionPerformed

