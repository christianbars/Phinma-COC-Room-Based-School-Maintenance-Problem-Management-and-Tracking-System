private void loadDropdowns() {
    try {
        EntityDAO dao = new EntityDAO();

        buildingComboBox.removeAllItems();
        problemTypeComboBox.removeAllItems();

        buildingIds.clear();
        roomTypeIds.clear();

        for (Building b : dao.getAllBuildings()) {
            buildingComboBox.addItem(b.getBuildingName());
            buildingIds.put(b.getBuildingName(), b.getBuildingId());
        }

        for (RoomType r : dao.getAllRoomTypes()) {
            problemTypeComboBox.addItem(r.getRoomTypeName());
            roomTypeIds.put(r.getRoomTypeName(), r.getRoomTypeId());
        }

        loadProblemTypesForSelectedRoom();

        jLabel13.setText("ROOM TYPE:");

    } catch (Exception e) {
        javax.swing.JOptionPane.showMessageDialog(
            this,
            "Unable to load dropdown choices from the database."
        );
        e.printStackTrace();
    }
}

private void loadProblemTypesForSelectedRoom() {
    problemComboBox.removeAllItems();
    problemTypeIds.clear();

    String roomType = (String) problemTypeComboBox.getSelectedItem();

    if (roomType == null) {
        return;
    }

    try {
        EntityDAO dao = new EntityDAO();

        for (ProblemType p : dao.getAllProblemTypes()) {
            String name = p.getProblemTypeName();
            boolean allowed = false;

            if ("Classroom".equalsIgnoreCase(roomType)) {
                allowed = name.equalsIgnoreCase("TV")
                    || name.equalsIgnoreCase("TABLE")
                    || name.equalsIgnoreCase("CHAIR")
                    || name.equalsIgnoreCase("BOARD")
                    || name.equalsIgnoreCase("WHITEBOARD")
                    || name.equalsIgnoreCase("OTHERS");

            } else if ("Computer Laboratory".equalsIgnoreCase(roomType)) {
                allowed = name.equalsIgnoreCase("PC")
                    || name.equalsIgnoreCase("TABLE")
                    || name.equalsIgnoreCase("CHAIR")
                    || name.equalsIgnoreCase("WHITEBOARD")
                    || name.equalsIgnoreCase("OTHERS");

            } else if ("Comfort Room".equalsIgnoreCase(roomType)) {
                allowed = name.equalsIgnoreCase("TOILET")
                    || name.equalsIgnoreCase("FAUCET")
                    || name.equalsIgnoreCase("SINK")
                    || name.equalsIgnoreCase("URINAL")
                    || name.equalsIgnoreCase("DOOR")
                    || name.equalsIgnoreCase("LIGHT")
                    || name.equalsIgnoreCase("OTHERS");
            }

            if (allowed) {
                problemComboBox.addItem(name);
               problemTypeIds.put(
               name.trim().toUpperCase(),
               p.getProblemTypeId()
);
            }
        }

        updateOtherProblemField();

    } catch (Exception e) {
        javax.swing.JOptionPane.showMessageDialog(
            this,
            "Unable to load problem types."
        );
        e.printStackTrace();
    }
}

private void updateOtherProblemField() {
    String selected = (String) problemComboBox.getSelectedItem();

    boolean isOthers = "OTHERS".equalsIgnoreCase(selected);

    otherProblemField.setVisible(isOthers);

    if (!isOthers) {
        otherProblemField.setText("");
    }

    jPanel2.revalidate();
    jPanel2.repaint();
}
