    private void acceptButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_acceptButtonActionPerformed
        String idText = problemIdValueLabel.getText().trim();

    if (idText.isEmpty()) {

        javax.swing.JOptionPane.showMessageDialog(
            this,
            "Invalid input. Please try again."
        );

        return;
    }

    int problemId;

    try {

        problemId = Integer.parseInt(idText);

    } catch (NumberFormatException e) {

        javax.swing.JOptionPane.showMessageDialog(
            this,
            "Invalid input. Please try again."
        );

        return;
    }

    boolean updated =
            ProblemDAO.updateStatus(
                problemId,
                "In Progress",
                ""
            );

    if (updated) {

        javax.swing.JOptionPane.showMessageDialog(
            this,
            "Problem accepted successfully."
        );

        MaintenanceDashboard dashboard =
                new MaintenanceDashboard();

        dashboard.setVisible(true);
        this.dispose();

    } else {

        javax.swing.JOptionPane.showMessageDialog(
            this,
            "Failed to accept the problem."
        );
    }
    }//GEN-LAST:event_acceptButtonActionPerformed

