   private void loadProblemsByStatus(String status) {

    javax.swing.table.DefaultTableModel model =
            (javax.swing.table.DefaultTableModel) problemTable.getModel();

    model.setRowCount(0);

    int no = 1;

    for (Data.ProblemData p : ProblemDAO.getAllProblems()) {

    if (status.equals(p.status)) {

        model.addRow(new Object[]{
            no,
            p.id,
            p.studentId,
            "OTHERS".equalsIgnoreCase(p.problem)
                    && p.otherProblem != null
                    && !p.otherProblem.trim().isEmpty()
                    ? p.otherProblem
                    : p.problem,
            p.building,
            p.room,
            p.status
        });

        no++;
    }
    }}
private void loadAllProblems() {

    javax.swing.table.DefaultTableModel model =
            (javax.swing.table.DefaultTableModel) problemTable.getModel();

    model.setRowCount(0);

    int no = 1;

    for (Data.ProblemData p : ProblemDAO.getAllProblems()) {

        String problemName = "OTHERS".equalsIgnoreCase(p.problem)
                && p.otherProblem != null
                && !p.otherProblem.trim().isEmpty()
                ? p.otherProblem
                : p.problem;

        model.addRow(new Object[]{
            no,
            p.id,
            p.studentId,
            problemName,
            p.building,
            p.room,
            p.status
        });

        no++;
    }
}
private void updateCounts() {

    int pending = 0;
    int inProgress = 0;
    int done = 0;
    int unfixed = 0;

    java.util.ArrayList<Data.ProblemData> problems =
            ProblemDAO.getAllProblems();

    for (Data.ProblemData p : problems) {

        if ("Pending".equals(p.status)) {
            pending++;
        } else if ("In Progress".equals(p.status)) {
            inProgress++;
        } else if ("Done".equals(p.status)) {
            done++;
        } else if ("Unfixed".equals(p.status)) {
            unfixed++;
        }
    }

    int total = problems.size();

    pendingCountLabel.setText(String.valueOf(pending));
    inProgressCountLabel.setText(String.valueOf(inProgress));
    doneCountLabel.setText(String.valueOf(done));
    unfixedCountLabel.setText(String.valueOf(unfixed));
    totalCountLabel.setText(String.valueOf(total));
}
    
    private void updateMaintenanceDates(int problemId) {

    Data.ProblemData problem =
            ProblemDAO.getProblemById(problemId);

    if (problem == null) {
        dateReportedValueLabel.setText("Not available");
        dateAcceptedValueLabel.setText("Not available");
        dateCompletedValueLabel.setText("Not available");
        dateUnfixedValueLabel.setText("Not available");
        return;
    }

    dateReportedValueLabel.setText(
            problem.dateReported.isEmpty()
                    ? "Not available"
                    : problem.dateReported);

    dateAcceptedValueLabel.setText(
            problem.dateAccepted.isEmpty()
                    ? "Not yet accepted"
                    : problem.dateAccepted);

    dateCompletedValueLabel.setText(
            problem.fixedDate.isEmpty()
                    ? "Not yet completed"
                    : problem.fixedDate);

    dateUnfixedValueLabel.setText(
            problem.dateUnfixed.isEmpty()
                    ? "Not applicable yet"
                    : problem.dateUnfixed);
}
    
