    private void searchTextFieldActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_searchTextFieldActionPerformed
String search = searchTextField.getText().trim();

    if (search.isEmpty() || search.equals("jTextField1")) {
        loadAllProblems();
        return;
    }

    javax.swing.table.DefaultTableModel model =
            (javax.swing.table.DefaultTableModel) problemTable.getModel();

    model.setRowCount(0);

    int no = 1;

    for (Data.ProblemData p : ProblemDAO.getAllProblems()) {

        String problemId = String.valueOf(p.id);
        String studentId = p.studentId == null ? "" : p.studentId;

        if (problemId.equalsIgnoreCase(search)
                || studentId.equalsIgnoreCase(search)) {

            String problemName = "OTHERS".equalsIgnoreCase(p.problem)
                    && p.otherProblem != null
                    && !p.otherProblem.trim().isEmpty()
                    ? p.otherProblem
                    : p.problem;

            model.addRow(new Object[]{
                no++,
                p.id,
                p.studentId,
                problemName,
                p.building,
                p.room,
                p.status
            });
        }
    }

    if (model.getRowCount() == 0) {
        javax.swing.JOptionPane.showMessageDialog(
                this,
                "No matching problem found."
        );
    }     
    }//GEN-LAST:event_searchTextFieldActionPerformed

