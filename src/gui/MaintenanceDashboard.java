    private void problemTableMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_problemTableMouseClicked

    int row = problemTable.rowAtPoint(evt.getPoint());

    if (row == -1) {
        return;
    }

    // Select the clicked row
    problemTable.setRowSelectionInterval(row, row);

    int modelRow = problemTable.convertRowIndexToModel(row);

    int problemId = Integer.parseInt(
        problemTable.getModel().getValueAt(modelRow, 1).toString()
    );

    // Display maintenance dates
    updateMaintenanceDates(problemId);

    // Open window only on double right-click
    if (evt.getClickCount() == 2
            && javax.swing.SwingUtilities.isRightMouseButton(evt)) {

        String status = problemTable.getModel()
            .getValueAt(modelRow, 6).toString().trim();

        if (status.equalsIgnoreCase("Pending")) {
            Pending pending = new Pending(problemId);
            pending.setLocationRelativeTo(this);
            pending.setVisible(true);
            this.dispose();

        } else if (status.equalsIgnoreCase("In Progress")) {
            InProgress inProgress = new InProgress(problemId);
            inProgress.setLocationRelativeTo(this);
            inProgress.setVisible(true);
            this.dispose();
        }
    }
    }//GEN-LAST:event_problemTableMouseClicked

    private void archiveButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_archiveButtonActionPerformed
      int selectedRow = problemTable.getSelectedRow();

    // No row selected
    if (selectedRow == -1) {
        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Please select a problem first."
        );
        return;
    }

    // Column 1 = actual database Problem ID
    int problemId = Integer.parseInt(
            problemTable.getValueAt(selectedRow, 1).toString()
    );

    // Get the problem from database
    Data.ProblemData problem =
            ProblemDAO.getProblemById(problemId);

    if (problem == null) {
        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Problem not found."
        );
        return;
    }

    // Only Done or Unfixed problems can be archived
    if (!problem.status.equalsIgnoreCase("Done")
            && !problem.status.equalsIgnoreCase("Unfixed")) {

        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Only Done or Unfixed problems can be archived."
        );
        return;
    }

    // Confirm archive
    int choice = javax.swing.JOptionPane.showConfirmDialog(
            this,
            "Are you sure you want to archive this problem?",
            "Confirm Archive",
            javax.swing.JOptionPane.YES_NO_OPTION
    );

    if (choice != javax.swing.JOptionPane.YES_OPTION) {
        return;
    }

    // Archive instead of deleting
    boolean archived =
            ProblemDAO.archiveProblem(problemId);

    if (archived) {

        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Problem archived successfully."
        );

        loadAllProblems();
        updateCounts();

    } else {

        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Unable to archive the problem."
        );
    }
    }//GEN-LAST:event_archiveButtonActionPerformed

